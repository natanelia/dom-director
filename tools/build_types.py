#!/usr/bin/env python3
"""Generate readonly authoring types from the canonical schemas, without dependencies.
Numeric bounds, patterns and semantic constraints still require runtime validation.
"""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
NAMES={'tour':'Tour','diagnostic':'Diagnostic','agent-command':'AgentCommand'}

def generate(folder):
    documents={name:json.loads((folder/(name+'.schema.json')).read_text()) for name in NAMES}
    ids={doc['$id']:name for name,doc in documents.items()}
    def literal(value):return json.dumps(value,ensure_ascii=True,separators=(',',':'))
    def typename(schema,name,context=None):
        if schema is True:return 'JsonValue'
        if schema is False:return 'never'
        if '$ref' in schema:
            ref=schema['$ref'];base,_,pointer=ref.partition('#')
            owner=ids[base] if base else name
            if not pointer:return NAMES[owner]
            if pointer.startswith('/$defs/'):
                key=pointer.split('/')[-1];return NAMES[owner]+key[:1].upper()+key[1:]
            raise ValueError('Unsupported reference '+ref)
        if 'const' in schema:return literal(schema['const'])
        if 'enum' in schema:return '('+' | '.join(map(literal,schema['enum']))+')'
        t=schema.get('type')
        if isinstance(t,list):return '('+' | '.join(typename({**schema,'type':item},name,context) for item in t)+')'
        props=schema.get('properties',{})
        inherited=context or props
        if t=='object' or props or 'required' in schema:
            required=set(schema.get('required',[]));fields=[]
            for key,value in props.items():fields.append('readonly '+literal(key)+('' if key in required else '?')+': '+typename(value,name)+';')
            for key in sorted(required-set(props)):
                fields.append('readonly '+literal(key)+': '+typename(inherited.get(key,{}),name)+';')
            forbidden=schema.get('not',{}).get('required',[])
            if len(forbidden)==1:fields.append('readonly '+literal(forbidden[0])+'?: never;')
            additional=schema.get('additionalProperties',True)
            if isinstance(additional,dict):fields.append('readonly [key: string]: '+typename(additional,name)+';')
            elif additional and not fields:fields.append('readonly [key: string]: JsonValue;')
            base='{ '+' '.join(fields)+' }' if fields else 'Readonly<Record<string, never>>'
        elif t=='array':base='ReadonlyArray<'+typename(schema.get('items',{}),name)+'>'
        elif t in ('integer','number'):base='number'
        elif t in ('string','boolean','null'):base=t
        else:base='unknown'
        for union in ['oneOf','anyOf','allOf']:
            if union in schema:
                parts=[typename(part,name,inherited) for part in schema[union]]
                joined='(' + (' & ' if union=='allOf' else ' | ').join(parts) + ')'
                base=joined if base=='unknown' else '('+base+' & '+joined+')'
        return 'JsonValue' if base=='unknown' else base
    result=['// Generated by tools/build_types.py from canonical schemas. Do not hand-edit.',
      '// Bounds, regexes, uniqueness and graph semantics are validated at runtime.',
      'export type JsonValue = null | boolean | number | string | ReadonlyArray<JsonValue> | {readonly [key: string]: JsonValue};']
    for name,doc in documents.items():
        for key,value in doc.get('$defs',{}).items():result.append('export type '+NAMES[name]+key[:1].upper()+key[1:]+' = '+typename(value,name)+';')
        result.append('export type '+NAMES[name]+' = '+typename(doc,name)+';')
    result += ['export type TourScene = Tour["scenes"][number];','export type TourCue = TourScene["cues"][number];',
      'export type TourTarget = Tour["targets"][string];','export type TourAsset = NonNullable<Tour["assets"]>[string];']
    return '\n\n'.join(result)+'\n'
if __name__=='__main__':
    target=ROOT/'packages/core/src/script.generated.d.ts';target.write_text(generate(ROOT/'schemas'),encoding='utf-8');print(f'Generated canonical types: {target.stat().st_size} bytes')
