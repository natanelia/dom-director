#!/usr/bin/env python3
"""Embed only the repository-owned canonical schemas; never fetch remote schemas."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'packages/core/src/schema.generated.js'

def main():
    schemas={name:json.loads((ROOT/f'schemas/{name}.schema.json').read_text(encoding='utf-8')) for name in ('tour','agent-command')}
    OUT.write_text('// Generated by tools/build_runtime.py; do not edit.\nexport const schemas = '+json.dumps(schemas,separators=(',',':'))+';\n',encoding='utf-8')
    print(f'Embedded canonical schemas: {OUT.stat().st_size} bytes')
if __name__=='__main__':main()
